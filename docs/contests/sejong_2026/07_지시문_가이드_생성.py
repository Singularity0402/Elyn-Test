# ================================================================ 검사(lint)
def inside(inner, outer, tol=0.004):
    ix, iy, iw, ih = inner
    ox, oy, ow, oh = outer
    return ix >= ox - tol and iy >= oy - tol and ix + iw <= ox + ow + tol and iy + ih <= oy + oh + tol


def overlap(a, b, tol=0.004):
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    return not (ax + aw <= bx + tol or bx + bw <= ax + tol or ay + ah <= by + tol or by + bh <= ay + tol)


def lint():
    errs, notes = [], []
    for c in CUTS:
        n = c["no"]
        zmap = {z["id"]: z["box"] for z in c["zones"]}
        key = [s for s in c["subjects"] if s.get("key")]
        for z in c["zones"]:
            if not inside(z["box"], [0, 0, 1, 1]):
                errs.append("컷%d 구역 %s 가 프레임 밖" % (n, z["id"]))
            for s in key:
                if overlap(z["box"], s["box"]):
                    errs.append("컷%d 구역 %s 가 핵심 사물 '%s' 와 겹침" % (n, z["id"], s.get("name")))
        area = 0.0
        els = c["elements"]
        for i, e in enumerate(els):
            if e["zone"] not in zmap or not inside(e["box"], zmap[e["zone"]]):
                errs.append("컷%d '%s' 가 구역 %s 밖" % (n, e["text"][:10], e["zone"]))
            area += e["box"][2] * e["box"][3]
            for s in key:
                if overlap(e["box"], s["box"]):
                    errs.append("컷%d '%s' 가 핵심 사물 '%s' 를 가림" % (n, e["text"][:10], s.get("name")))
            for e2 in els[i + 1:]:
                if overlap(e["box"], e2["box"]):
                    errs.append("컷%d 글 상자끼리 겹침: '%s' / '%s'" % (n, e["text"][:8], e2["text"][:8]))
            if e.get("tail"):
                tx, ty = e["tail"]
                kind_need = {"호랑이": "tiger", "후드 시민": "hood"}.get(e.get("who"))
                ok = False
                for s in key:
                    b = s["box"]
                    match = (s["kind"] == kind_need) if kind_need else ("도어벨" in (s.get("name") or ""))
                    if match and b[0] - .02 <= tx <= b[0] + b[2] + .02 and b[1] - .02 <= ty <= b[1] + b[3] + .02:
                        ok = True
                if not ok:
                    errs.append("컷%d 말풍선 꼬리 목표(%.2f,%.2f)가 화자(%s)의 사물 안에 없음" % (n, tx, ty, e.get("who")))
        if area > 0.25:
            errs.append("컷%d 글 상자 면적 %.0f%% > 25%%" % (n, area * 100))
        else:
            notes.append("컷%d 글 상자 면적 %.0f%%" % (n, area * 100))
        cam = c.get("camera")
        if cam and cam["eye"] < 1.5:
            for s in c["subjects"]:
                if s["kind"] in ("person", "hood", "tiger") and s["box"][1] >= cam["horizon"] - 1e-6:
                    errs.append("컷%d '%s'(%s)의 머리 윗부분이 수평선(%.2f) 아래: 눈높이 %.1fm 시점과 모순" % (n, s.get("name") or s.get("pose"), s["kind"], cam["horizon"], cam["eye"]))
    c1 = [c for c in CUTS if c["no"] == 1][0]
    c8 = [c for c in CUTS if c["no"] == 8][0]
    if c1["camera"] != c8["camera"]:
        errs.append("컷 1과 컷 8의 카메라 값이 다름")
    bg1 = [s for s in c1["subjects"] if s["kind"] in ("rect", "poly", "ellipse") and s["name"] not in ("호랑이 그림자", "호랑이 그림자(작게)")]
    bg8 = [s for s in c8["subjects"] if s["kind"] in ("rect", "poly", "ellipse") and s["name"] not in ("호랑이 그림자", "호랑이 그림자(작게)")]
    if [(s["box"], s["color"]) for s in bg1] != [(s["box"], s["color"]) for s in bg8]:
        errs.append("컷 1과 컷 8의 배경 사물 배치가 다름")
    return errs, notes


