def zone_table(c):
    rows = ["| 구역 | 4:5 프레임 좌표 (x, y, w, h) | 1440x1800 픽셀 | 비워 둘 면 | 평면 필수 |", "|---|---|---|---|---|"]
    for z in c["zones"]:
        b = z["box"]
        rows.append("| %s | (%.3f, %.3f, %.3f, %.3f) | (%d, %d, %d, %d) | %s | %s |" % (
            z["id"], b[0], b[1], b[2], b[3], b[0] * 1440, b[1] * 1800, b[2] * 1440, b[3] * 1800, z["desc"],
            "예(글자가 그림 위에 그대로 얹힘)" if zone_strict(c, z["id"]) else "아니오(불투명 상자가 덮음)"))
    return "\n".join(rows)


def element_table(c):
    kn = {"title": "제목", "sub": "부제", "sfx": "효과음", "nar": "해설 상자", "say": "말풍선", "radio": "기계음 상자", "caption": "마무리 자막"}
    rows = ["| 종류 | 화자 | 글 | 상자 (x, y, w, h) | 구역 | 꼬리 |", "|---|---|---|---|---|---|"]
    for e in c["elements"]:
        b = e["box"]
        rows.append("| %s | %s | %s | (%.3f, %.3f, %.3f, %.3f) | %s | %s |" % (
            kn.get(e["kind"], e["kind"]), e.get("who", "-"), e["text"].replace("\n", " / "), b[0], b[1], b[2], b[3], e["zone"],
            ("(%.2f, %.2f)" % tuple(e["tail"])) if e.get("tail") else "-"))
    return "\n".join(rows)


