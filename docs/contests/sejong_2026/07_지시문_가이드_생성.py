def y23(y):
    """4:5 프레임 y(0~1) -> 2:3 캔버스 y(0~1)"""
    return (128 + y * 1280) / 1536.0


def pct_box(box):
    x, y, w, h = box
    x0, x1 = round(x * 100), round((x + w) * 100)
    cut = ""
    if x0 < 0 or x1 > 100:
        cut = "(화면 밖으로 잘림)"
    return "가로 %d~%d%%%s, 세로 %d~%d%%" % (max(0, x0), min(100, x1), cut,
                                          round(y23(y) * 100), round(y23(y + h) * 100))


