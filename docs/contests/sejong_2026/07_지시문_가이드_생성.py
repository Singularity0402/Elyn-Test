def draw_guides(outdir):
    from PIL import Image, ImageDraw, ImageFont
    outdir.mkdir(exist_ok=True)
    W, H = 1024, 1536
    FW, FH = 1024, 1280
    OY = 128

    def X(x):
        return x * FW

    def Y(y):
        return OY + y * FH

    def hexc(h):
        return h

    def draw_tiger(d, b, pose, cutno):
        x, y, w, h = b
        ORG, INK, CRM, YEL, PNK = "#E8591A", "#1B1B22", "#F4F1E8", "#F2C230", "#D9A5A0"
        px, py, pw, ph = X(x), Y(y), w * FW, h * FH
        cx = px + pw / 2
        if pose == "squish":
            d.ellipse([px, py, px + pw, py + ph], fill=ORG, outline=INK, width=6)
            for k in range(3):
                yy = py + ph * (0.14 + k * 0.05)
                d.line([cx - pw * .15, yy, cx + pw * .15, yy], fill=INK, width=7)
            for sx in (-1, 1):
                d.line([cx + sx * pw * .30, py + ph * .42, cx + sx * pw * .12, py + ph * .40], fill=INK, width=8)
                d.ellipse([cx + sx * pw * .22 - 14, py + ph * .42, cx + sx * pw * .22 + 14, py + ph * .47], fill=YEL, outline=INK, width=3)
            d.ellipse([cx - 20, py + ph * .55, cx + 20, py + ph * .62], fill=INK)
            d.arc([cx - pw * .15, py + ph * .70, cx + pw * .15, py + ph * .86], 200, 340, fill=INK, width=8)
            return
        head_h = ph * 0.34
        head_w = min(pw * 0.62, head_h * 1.15)
        body_top = py + head_h * 0.85
        if pose == "slump":
            body_top = py + head_h * 0.95
        d.ellipse([px + pw * .12, body_top, px + pw * .88, py + ph], fill=ORG, outline=INK, width=5)
        d.ellipse([cx - pw * .17, body_top + ph * .18, cx + pw * .17, py + ph * .92], fill=CRM)
        hx0, hy0 = cx - head_w / 2, py
        if pose in ("smug",):
            hx0 = px + pw * 0.25
        d.ellipse([hx0, hy0, hx0 + head_w, hy0 + head_h], fill=ORG, outline=INK, width=5)
        for sx in (hx0 + head_w * .08, hx0 + head_w * .92):
            d.ellipse([sx - head_w * .12, hy0 - head_h * .05, sx + head_w * .12, hy0 + head_h * .22], fill=ORG, outline=INK, width=4)
        hc = hx0 + head_w / 2
        if pose != "back":
            for k in range(3):
                yy = hy0 + head_h * (0.14 + k * 0.06)
                d.line([hc - head_w * .12, yy, hc + head_w * .12, yy], fill=INK, width=5)
            if pose in ("smug",):
                for sx in (-1, 1):
                    d.line([hc + sx * head_w * .30, hy0 + head_h * .44, hc + sx * head_w * .12, hy0 + head_h * .46], fill=INK, width=6)
            else:
                for sx in (-1, 1):
                    d.ellipse([hc + sx * head_w * .22 - 9, hy0 + head_h * .38, hc + sx * head_w * .22 + 9, hy0 + head_h * .38 + 18], fill=YEL, outline=INK, width=2)
            d.ellipse([hc - head_w * .24, hy0 + head_h * .60, hc + head_w * .24, hy0 + head_h * .92], fill=CRM, outline=INK, width=3)
            if pose in ("front", "lunge", "demand"):
                d.ellipse([hc - head_w * .15, hy0 + head_h * .70, hc + head_w * .15, hy0 + head_h * .92], fill=INK)
            d.ellipse([hc - 9, hy0 + head_h * .60, hc + 9, hy0 + head_h * .68], fill=INK)
        if pose == "front":
            d.line([px + pw * .15, body_top + ph * .15, px, body_top - ph * .05], fill=ORG, width=int(pw * .13))
            d.line([px + pw * .85, body_top + ph * .15, px + pw, body_top - ph * .05], fill=ORG, width=int(pw * .13))
        if pose == "back":
            d.line([px + pw * .92, py + ph * .90, px + pw * 1.0, py + ph * .62], fill=ORG, width=int(pw * .08))
            for k in range(5):
                t = k / 5.0
                qx = px + pw * (.92 + .08 * t)
                qy = py + ph * (.90 - .28 * t)
                d.line([qx - 6, qy, qx + 6, qy], fill=INK, width=4)
        if pose == "disguise":
            d.polygon([(hc - head_w * .5, hy0 + head_h * .2), (hc + head_w * .5, hy0 + head_h * .2), (hc + head_w * .4, hy0 + head_h * .52), (hc - head_w * .4, hy0 + head_h * .52)], fill=PNK, outline=INK)
