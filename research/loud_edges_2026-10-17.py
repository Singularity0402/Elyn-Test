"""
1차 검증 (2026-10-17, 데이터 없이) — "빠른 엣지는 숨을 수 없다"와 선구자 트랙(P14·P15)의 설계 검정력.

1. 연 로그성장 g 로 불리는 전략은 엣지 정보(연 거래 수 × 거래당 샤프²) ≥ 약 2g 이다(L25: 천장 = 엣지 정보 ÷ 2).
   T 년 기록의 t값 = 거래당 샤프 × √(거래 수) = √(엣지 정보 × T) 이므로 **t ≥ √(2gT)**. 빠르면 반드시 시끄럽다.
   (반대는 아니다: 캐리는 시끄럽지만 레버리지를 못 써서 느리다.)
2. 규칙을 M 개 뒤지면 운만으로 나오는 1등 t값(본페로니 단측 5%)은 √(2 ln M) 정도로 아주 천천히 오른다.
   → 대규모 탐색은 "큰 엣지"(하루 1%급)는 운과 구분하지만, 작은 엣지(BNF급 이하)는 못 잡는다. 작은 것은 바깥 고정 규칙으로(L24).
3. P15 극단 펀딩 캐리의 본전 계산.
실행: python research/loud_edges_2026-10-17.py   (결과: loud_edges_2026-10-17_output.txt)
"""
import math

# 엣지 정보 = 연 거래 수 × 거래당 샤프² (mc_plan_2026-10-17.py kelly 의 값). 반켈리는 같은 속도에 엣지 정보가 4/3 배 필요하다.
INFO = [('지금 확인된 셋', 1.10), ('BNF·미너비니급 (하루 약 0.3%)', 2.33), ('하루 1% (켈리)', 7.26), ('하루 1% (반켈리)', 9.68)]


def ncdf(x):
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def nppf(p):
    lo, hi = -40.0, 40.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if ncdf(mid) < p:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def bar(M, alpha=0.05):
    """규칙 M 개 중 운만으로 넘기 어려운 t (본페로니 단측). 규칙끼리 겹치면 실제 한도는 이보다 조금 낮다."""
    return -nppf(alpha / M) if M > 1 else -nppf(alpha)


def main():
    print('[1] 과거 T년 기록에서 보여야 하는 t값 = √(엣지 정보 × T)')
    wins = [('P9 찾기 구간 2.5년', 2.5), ('P9 검증 두 구간 합 4.6년', 4.6), ('미결제약정 자료 약 4.8년', 4.8), ('BTC 4h 전체 8.8년', 8.8),
            ('실전 6개월', 0.5), ('실전 1년', 1.0)]
    for nm, info in INFO:
        print(f'  {nm} (엣지 정보 {info:.2f}): ' + ' · '.join(f'{w} t≈{math.sqrt(info * T):.1f}' for w, T in wins))
    print('\n[2] 규칙 M 개를 뒤질 때 운의 한도 (본페로니 단측 5%)')
    for M in (1, 20, 9756, 10 ** 5, 10 ** 6, 10 ** 7, 10 ** 8, 10 ** 9):
        print(f'  M = {M:>13,}: t > {bar(M):.2f}')
    print('\n[3] P9가 하루 1%급 엣지를 놓쳤을 확률 (그 규칙 공간 안에 있었다면)')
    mu = math.sqrt(7.26 * 2.5)
    p_top = 1 - ncdf(2.90 - mu)                                  # 찾기 구간에서 실제 1등(2.90)보다 높게 나올 확률
    p_val = 1 - ncdf(-nppf(0.0025) - math.sqrt(7.26 * 4.6))     # 검증 두 구간 합산 하한 > 0
    print(f'  찾기 구간 기대 t {mu:.2f} → 실제 1등 2.90보다 높게 나올 확률 {p_top:.0%} · 검증 통과 확률 {p_val:.1%} '
          f'→ 찾았을 확률 약 {p_top * p_val:.0%}, 놓쳤을 확률 약 {1 - p_top * p_val:.0%}')
    print('\n[4] P14 대규모 탐색의 검정력 (자료 4.8년, 엣지가 그 기간 내내 살아 있었다면)')
    for M in (10 ** 4, 10 ** 5, 10 ** 6):
        b = bar(M)
        row = []
        for nm, info in INFO:
            row.append(f'{nm} {1 - ncdf(b - math.sqrt(info * 4.8)):.0%}')
        print(f'  M = {M:>9,} (한도 {b:.2f}): ' + ' · '.join(row))
    print('\n[5] P15 극단 펀딩 캐리 본전 (현물 매수 + 무기한 숏 같은 금액, 왕복 비용 = 현물 0.1%×2 + 선물 0.05%×2 + 미끄러짐 0.05% = 0.35%)')
    cost = 0.35
    print('  8시간 펀딩 \\ 정산 횟수 :  ' + '  '.join(f'{k:>5}회' for k in (1, 3, 6, 9, 21)))
    for f in (0.03, 0.05, 0.10, 0.20, 0.30):
        print(f'  {f:.2f}%               :  ' + '  '.join(f'{k * f - cost:+6.2f}%' for k in (1, 3, 6, 9, 21)))
    print('  (명목 기준. 선물 쪽 증거금을 명목과 같게 두면 자본은 명목의 2배라, 자본 기준 수익은 이 값의 절반이다.)')
    print('  본전 정산 횟수: ' + ' · '.join(f'{f:.2f}% → {cost / f:.1f}회' for f in (0.03, 0.05, 0.10, 0.20, 0.30)))
    for f, per_day in ((0.10, 3), (0.20, 3)):
        d = per_day * f / 2                                       # 자본 기준 하루 수익(비용 전)
        print(f'  펀딩 {f:.2f}%/8h 가 끊이지 않고 이어지면 자본 기준 하루 약 {d:.2f}% (비용 전) — 실제로는 극단이 며칠만 간다')


if __name__ == '__main__':
    main()
